DO $postcondition$
DECLARE
  v_table text;
  v_policy text;
  v_sequence text;
BEGIN
  IF (SELECT count(*) FROM pg_catalog.pg_class AS c
      JOIN pg_catalog.pg_namespace AS n ON n.oid = c.relnamespace
      WHERE n.nspname = 'public' AND c.relkind = 'r'
        AND c.relname IN ('payroll_periods','work_periods','work_period_versions','work_period_anomalies')) <> 4 THEN
    RAISE EXCEPTION 'MIGRATION_10_POSTCONDITION: expected four canonical tables';
  END IF;

  FOR v_table, v_policy IN SELECT * FROM (VALUES
    ('payroll_periods', 'Active Manager/Owner can read payroll periods'),
    ('work_periods', 'Active Manager/Owner can read work periods'),
    ('work_period_versions', 'Active Manager/Owner can read work period versions'),
    ('work_period_anomalies', 'Active Manager/Owner can read work period anomalies')
  ) AS x(table_name, policy_name)
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_catalog.pg_class AS c
      JOIN pg_catalog.pg_namespace AS n ON n.oid = c.relnamespace
      WHERE n.nspname = 'public' AND c.relname = v_table
        AND c.relrowsecurity AND NOT c.relforcerowsecurity
    ) OR NOT EXISTS (
      SELECT 1 FROM pg_catalog.pg_policies AS p
      WHERE p.schemaname = 'public' AND p.tablename = v_table
        AND p.policyname = v_policy AND p.cmd = 'SELECT'
        AND p.roles = ARRAY['authenticated']::name[]
    ) THEN
      RAISE EXCEPTION 'MIGRATION_10_POSTCONDITION: RLS contract failed for %', v_table;
    END IF;

    IF NOT pg_catalog.has_table_privilege('authenticated', 'public.' || v_table, 'SELECT')
       OR pg_catalog.has_table_privilege('authenticated', 'public.' || v_table, 'INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER')
       OR pg_catalog.has_table_privilege('anon', 'public.' || v_table, 'SELECT,INSERT,UPDATE,DELETE,TRUNCATE,REFERENCES,TRIGGER') THEN
      RAISE EXCEPTION 'MIGRATION_10_POSTCONDITION: table ACL failed for %', v_table;
    END IF;
  END LOOP;

  FOREACH v_sequence IN ARRAY ARRAY[
    'payroll_periods_id_seq', 'work_periods_id_seq',
    'work_period_versions_id_seq', 'work_period_anomalies_id_seq'
  ] LOOP
    IF pg_catalog.to_regclass('public.' || v_sequence) IS NULL
       OR pg_catalog.has_sequence_privilege('authenticated', 'public.' || v_sequence, 'USAGE,SELECT,UPDATE')
       OR pg_catalog.has_sequence_privilege('anon', 'public.' || v_sequence, 'USAGE,SELECT,UPDATE') THEN
      RAISE EXCEPTION 'MIGRATION_10_POSTCONDITION: sequence ACL failed for %', v_sequence;
    END IF;
  END LOOP;

  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_constraint WHERE conname = 'work_periods_current_version_same_period_fk')
     OR NOT EXISTS (SELECT 1 FROM pg_catalog.pg_constraint WHERE conname = 'work_period_anomalies_resolution_same_period_fk')
     OR NOT EXISTS (SELECT 1 FROM pg_catalog.pg_indexes WHERE schemaname='public' AND indexname='work_periods_time_clock_unique')
     OR NOT EXISTS (SELECT 1 FROM pg_catalog.pg_indexes WHERE schemaname='public' AND indexname='work_period_anomalies_open_type_unique') THEN
    RAISE EXCEPTION 'MIGRATION_10_POSTCONDITION: required integrity objects are missing';
  END IF;
END
