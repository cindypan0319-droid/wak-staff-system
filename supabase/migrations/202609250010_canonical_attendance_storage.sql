$precondition$;

CREATE TABLE public.payroll_periods (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  store_id text NOT NULL,
  week_start date NOT NULL,
  week_end date NOT NULL,
  timezone text NOT NULL DEFAULT 'Australia/Melbourne',
  shadow_status text NOT NULL DEFAULT 'BUILDING',
  generation_version integer NOT NULL DEFAULT 1,
  last_refreshed_at timestamptz NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT payroll_periods_pkey PRIMARY KEY (id),
  CONSTRAINT payroll_periods_store_week_key UNIQUE (store_id, week_start),
  CONSTRAINT payroll_periods_week_range_check CHECK (week_end = week_start + 6),
  CONSTRAINT payroll_periods_thursday_check CHECK (EXTRACT(DOW FROM week_start) = 4),
  CONSTRAINT payroll_periods_timezone_check CHECK (timezone = 'Australia/Melbourne'),
  CONSTRAINT payroll_periods_shadow_status_check CHECK (
    shadow_status IN ('BUILDING', 'READY_FOR_COMPARISON', 'ERROR')
  ),
  CONSTRAINT payroll_periods_generation_version_check CHECK (generation_version > 0)
);

CREATE TABLE public.work_periods (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  store_id text NOT NULL,
  staff_id uuid NOT NULL,
  payroll_period_id bigint NOT NULL,
  source_type text NOT NULL,
  time_clock_id bigint NULL,
  matched_shift_id bigint NULL,
  status text NOT NULL DEFAULT 'NEEDS_REVIEW',
  current_version_id bigint NULL,
  created_by uuid NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT work_periods_pkey PRIMARY KEY (id),
  CONSTRAINT work_periods_staff_fk FOREIGN KEY (staff_id)
    REFERENCES public.profiles(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT work_periods_payroll_period_fk FOREIGN KEY (payroll_period_id)
    REFERENCES public.payroll_periods(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT work_periods_time_clock_fk FOREIGN KEY (time_clock_id)
    REFERENCES public.time_clock(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT work_periods_matched_shift_fk FOREIGN KEY (matched_shift_id)
    REFERENCES public.shifts(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT work_periods_created_by_fk FOREIGN KEY (created_by)
    REFERENCES public.profiles(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT work_periods_source_type_check CHECK (source_type IN ('CLOCK', 'MANUAL_NO_CLOCK')),
  CONSTRAINT work_periods_status_check CHECK (status IN ('NEEDS_REVIEW', 'READY', 'VOIDED')),
  CONSTRAINT work_periods_source_consistency_check CHECK (
    (source_type = 'CLOCK' AND time_clock_id IS NOT NULL)
    OR
    (source_type = 'MANUAL_NO_CLOCK' AND time_clock_id IS NULL AND created_by IS NOT NULL)
  )
);

CREATE UNIQUE INDEX work_periods_time_clock_unique
  ON public.work_periods (time_clock_id) WHERE time_clock_id IS NOT NULL;
CREATE INDEX work_periods_period_status_idx
  ON public.work_periods (payroll_period_id, status);
CREATE INDEX work_periods_staff_period_idx
  ON public.work_periods (staff_id, payroll_period_id);
CREATE INDEX work_periods_matched_shift_idx
  ON public.work_periods (matched_shift_id) WHERE matched_shift_id IS NOT NULL;

CREATE TABLE public.work_period_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  work_period_id bigint NOT NULL,
  version_number integer NOT NULL,
  disposition text NOT NULL DEFAULT 'ACTIVE',
  matched_shift_id bigint NULL,
  actual_start_at timestamptz NULL,
  actual_end_at timestamptz NULL,
  payable_start_at timestamptz NULL,
  payable_end_at timestamptz NULL,
  reason_code text NOT NULL,
  reason_note text NULL,
  change_source text NOT NULL,
  created_by uuid NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT work_period_versions_pkey PRIMARY KEY (id),
  CONSTRAINT work_period_versions_period_version_key UNIQUE (work_period_id, version_number),
  CONSTRAINT work_period_versions_id_period_key UNIQUE (id, work_period_id),
  CONSTRAINT work_period_versions_work_period_fk FOREIGN KEY (work_period_id)
    REFERENCES public.work_periods(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT work_period_versions_matched_shift_fk FOREIGN KEY (matched_shift_id)
    REFERENCES public.shifts(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT work_period_versions_created_by_fk FOREIGN KEY (created_by)
    REFERENCES public.profiles(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT work_period_versions_number_check CHECK (version_number > 0),
  CONSTRAINT work_period_versions_disposition_check CHECK (disposition IN ('ACTIVE', 'VOIDED')),
  CONSTRAINT work_period_versions_change_source_check CHECK (
    change_source IN ('SYSTEM', 'MANAGER', 'OWNER', 'LEGACY_IMPORT')
  ),
  CONSTRAINT work_period_versions_actual_range_check CHECK (
    actual_start_at IS NULL OR actual_end_at IS NULL OR actual_end_at > actual_start_at
  ),
  CONSTRAINT work_period_versions_payable_range_check CHECK (
    payable_start_at IS NULL OR payable_end_at IS NULL OR payable_end_at > payable_start_at
  ),
  CONSTRAINT work_period_versions_reason_code_check CHECK (btrim(reason_code) <> ''),
  CONSTRAINT work_period_versions_other_note_check CHECK (
    reason_code <> 'OTHER' OR (reason_note IS NOT NULL AND btrim(reason_note) <> '')
  ),
  CONSTRAINT work_period_versions_actor_check CHECK (
    change_source NOT IN ('MANAGER', 'OWNER') OR created_by IS NOT NULL
  )
);

