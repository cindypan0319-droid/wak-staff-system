    FOREIGN KEY (resolution_version_id, work_period_id)
    REFERENCES public.work_period_versions(id, work_period_id)
    ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT work_period_anomalies_type_check CHECK (anomaly_type IN (
    'MISSING_CLOCK_IN', 'MISSING_CLOCK_OUT', 'EARLY_START', 'LATE_START',
    'EARLY_FINISH', 'LATE_FINISH', 'UNROSTERED_WORK', 'AMBIGUOUS_MATCH',
    'OVERLAPPING_CLOCK', 'DUPLICATE_CLOCK', 'MISSED_CLOCK_OUT',
    'INVALID_CLOCK_RANGE', 'CROSSES_MIDNIGHT', 'SHIFT_STAFF_MISMATCH',
    'SOURCE_CHANGED_AFTER_REVIEW'
