  id bigint GENERATED BY DEFAULT AS IDENTITY,
  work_period_id bigint NOT NULL,
  anomaly_type text NOT NULL,
  severity text NOT NULL,
  status text NOT NULL DEFAULT 'OPEN',
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  detected_at timestamptz NOT NULL DEFAULT now(),
  resolved_by uuid NULL,
  resolved_at timestamptz NULL,
  resolution_reason_code text NULL,
  resolution_note text NULL,
  resolution_version_id bigint NULL,
  CONSTRAINT work_period_anomalies_pkey PRIMARY KEY (id),
  CONSTRAINT work_period_anomalies_work_period_fk FOREIGN KEY (work_period_id)
    REFERENCES public.work_periods(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
  CONSTRAINT work_period_anomalies_resolved_by_fk FOREIGN KEY (resolved_by)
    REFERENCES public.profiles(id) ON UPDATE NO ACTION ON DELETE NO ACTION,
