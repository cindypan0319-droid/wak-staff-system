  CONSTRAINT work_period_anomalies_status_check CHECK (status IN ('OPEN', 'RESOLVED', 'DISMISSED')),
  CONSTRAINT work_period_anomalies_details_check CHECK (jsonb_typeof(details) = 'object'),
  CONSTRAINT work_period_anomalies_other_note_check CHECK (
    resolution_reason_code IS DISTINCT FROM 'OTHER'
    OR (resolution_note IS NOT NULL AND btrim(resolution_note) <> '')
  )
